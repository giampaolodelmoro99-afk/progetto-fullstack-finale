<?php

namespace Database\Factories;

use App\Models\Category;
use App\Models\Product;
use Illuminate\Database\Eloquent\Factories\Factory;

/**
 * @extends Factory<Product>
 */
class ProductFactory extends Factory
{
    private const NOUNS = ['Cuffie', 'Auricolari', 'Diffusore', 'Radio', 'Caricatore', 'Cavo', 'Supporto', 'Orologio', 'Lampada', 'Tastiera', 'Batteria', 'Custodia'];

    private const EVOCATIVE_NAMES = ['Aria', 'Brezza', 'Seta', 'Colle', 'Eco', 'Onda', 'Faro', 'Meridiana', 'Sussurro', 'Vento', 'Riva', 'Aurora', 'Quercia', 'Marea'];

    private const SHORT_DESCRIPTIONS = [
        'Linee essenziali e materiali scelti per durare nel tempo.',
        'Pensato per accompagnarti ogni giorno, a casa e in viaggio.',
        'Suono pulito e bilanciato in un corpo compatto.',
        'Ricarica rapida e sicura per tutti i tuoi dispositivi.',
        'Un dettaglio discreto che mette ordine sulla scrivania.',
    ];

    private const PARAGRAPHS = [
        'Ogni componente è stato scelto per offrire prestazioni costanti nel tempo, senza rinunciare a un aspetto sobrio.',
        'Le finiture opache resistono ai graffi e alle impronte, così l\'oggetto resta bello anche dopo anni di uso quotidiano.',
        'La confezione è in cartone riciclato e contiene tutto il necessario per iniziare subito.',
        'Il design compatto trova posto ovunque: sulla scrivania, sul comodino o nello zaino.',
    ];

    private const SPECIFICATIONS = [
        ['label' => 'Dimensioni', 'value' => '18 × 18 × 34 cm'],
        ['label' => 'Peso', 'value' => '420 g'],
        ['label' => 'Potenza', 'value' => '65 W'],
        ['label' => 'Autonomia', 'value' => '30 ore'],
        ['label' => 'Connessione', 'value' => 'Bluetooth 5.3'],
        ['label' => 'Materiali', 'value' => 'Alluminio anodizzato'],
        ['label' => 'Colore', 'value' => 'Grafite'],
        ['label' => 'Garanzia', 'value' => '2 anni'],
        ['label' => 'Lunghezza', 'value' => '1 m'],
        ['label' => 'Ricarica', 'value' => 'USB-C'],
    ];

    /**
     * Active and well above every stock threshold. The slug is generated by ProductObserver.
     *
     * @return array<string, mixed>
     */
    public function definition(): array
    {
        return [
            'category_id' => Category::factory(),
            'name' => fake()->randomElement(self::NOUNS).' '.fake()->randomElement(self::EVOCATIVE_NAMES),
            'sku' => fake()->unique()->regexify('CDS-(AUD|RIC|SCR|IND|CAS)-[0-9]{3}'),
            'short_description' => fake()->randomElement(self::SHORT_DESCRIPTIONS),
            'description' => implode("\n\n", fake()->randomElements(self::PARAGRAPHS, 2)),
            'specifications' => fake()->randomElements(self::SPECIFICATIONS, fake()->numberBetween(4, 8)),
            'price' => fake()->numberBetween(9, 499) * 100 + 90,
            'stock' => fake()->numberBetween(11, 50),
            'is_active' => true,
        ];
    }

    public function inactive(): static
    {
        return $this->state(fn (array $attributes) => [
            'is_active' => false,
        ]);
    }

    public function outOfStock(): static
    {
        return $this->state(fn (array $attributes) => [
            'stock' => 0,
        ]);
    }

    /**
     * Within the "Ultimi N pezzi" threshold shown to customers.
     */
    public function lastUnits(int $stock = 2): static
    {
        return $this->state(fn (array $attributes) => [
            'stock' => $stock,
        ]);
    }

    /**
     * Within the admin low stock threshold, above the customer one.
     */
    public function lowStock(int $stock = 4): static
    {
        return $this->state(fn (array $attributes) => [
            'stock' => $stock,
        ]);
    }

    public function newArrival(): static
    {
        return $this->state(fn (array $attributes) => [
            'created_at' => now()->subDays(5),
        ]);
    }

    public function older(): static
    {
        return $this->state(fn (array $attributes) => [
            'created_at' => now()->subDays(90),
        ]);
    }

    public function trashed(): static
    {
        return $this->state(fn (array $attributes) => [
            'deleted_at' => now(),
        ]);
    }
}
