<?php

namespace Database\Factories;

use App\Models\Category;
use Illuminate\Database\Eloquent\Factories\Factory;

/**
 * @extends Factory<Category>
 */
class CategoryFactory extends Factory
{
    private const NAMES = [
        'Audio',
        'Ricarica',
        'Scrivania',
        'Indossabili',
        'Casa smart',
        'Viaggio',
        'Fotografia',
        'Ufficio',
        'Illuminazione',
        'Archiviazione',
    ];

    private const DESCRIPTIONS = [
        'Accessori scelti per durare',
        'Oggetti essenziali per ogni giorno',
        'Strumenti pensati per lavorare meglio',
        'Piccoli comfort per la casa',
        'Compagni di viaggio leggeri',
    ];

    /**
     * The slug is generated by CategoryObserver.
     *
     * @return array<string, mixed>
     */
    public function definition(): array
    {
        return [
            'name' => fake()->randomElement(self::NAMES).' '.fake()->unique()->numberBetween(1, 99999),
            'description' => fake()->randomElement(self::DESCRIPTIONS),
        ];
    }
}
